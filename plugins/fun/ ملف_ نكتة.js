/* ═══════════════════════════════════════════
   🎯 المعالج الرئيسي — بدون آيات
   ═══════════════════════════════════════════ */
const handler = async (m, { conn }) => {
    try {
        const chatId = m.chat;

        /* ✅ رياكت فوري */
        conn.sendMessage(chatId, {
            react: { text: '😂', key: m.key }
        }).catch(() => {});

        const randomIndex = Math.floor(Math.random() * jokesList.length);
        const randomJoke = jokesList[randomIndex];

        /* ✅ تصميم مضغوط — بدون آيات */
        const bodyText = `${BRAND.emoji} *نكتة*

━━━━━
${randomJoke}
━━━━━

${BRAND.emoji} *${BRAND.shortName}*`;

        /* ✅ sendButton — بدون صورة */
        try {
            await conn.sendButton(chatId, {
                bodyText: bodyText,
                footerText: `${BRAND.emoji} ${BRAND.botName}`,
                buttons: [
                    {
                        name: 'quick_reply',
                        params: {
                            display_text: `😂 نكتة أخرى`,
                            id: `.نكتة`
                        }
                    },
                    {
                        name: 'cta_url',
                        params: {
                            display_text: `📢 قناة البوت`,
                            url: BRAND.channelLink
                        }
                    }
                ],
                mentions: [m.sender],
                newsletter: {
                    name: BRAND.channelName,
                    jid: BRAND.channelId
                },
                interactiveConfig: { buttons_limits: 2 }
            }, m);
        } catch (e) {
            /* 🅱️ Fallback نصي */
            await conn.sendMessage(chatId, {
                text: bodyText,
                contextInfo: {
                    forwardingScore: 1,
                    isForwarded: true,
                    forwardedNewsletterMessageInfo: {
                        newsletterJid: BRAND.channelId,
                        newsletterName: BRAND.channelName,
                        serverMessageId: -1
                    }
                }
            }, { quoted: m });
        }

    } catch (error) {
        console.error(`${BRAND.emoji} خطأ:`, error);
        await conn.sendMessage(m.chat, {
            text: `${BRAND.emoji} *فشل إرسال النكتة*
━━━━━
📌 حاول مرة أخرى`
        }, { quoted: m });
    }
};

