/* ═══════════════════════════════════════════
   🎯 دالة جلب الاسم
   ═══════════════════════════════════════════ */
async function getUserName(conn, jid) {
    try {
        if (typeof conn.getName === 'function') {
            return await conn.getName(jid);
        }
        if (typeof conn.getNameById === 'function') {
            return await conn.getNameById(jid);
        }
        if (typeof conn.getNameWithJid === 'function') {
            return await conn.getNameWithJid(jid);
        }
    } catch (e) {
        /* صامت */
    }
    return jid.split('@')[0];
}

/* ═══════════════════════════════════════════
   🎯 المعالج الرئيسي — بدون آيات
   ═══════════════════════════════════════════ */
const handler = async (m, { conn, command }) => {
    const chatId = m.chat;

    /* ✅ للمجموعات فقط */
    if (!m.isGroup) {
        return m.reply(`${BRAND.emoji} *للمجموعات فقط*
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`);
    }

    try {
        /* ✅ جلب المشاركين */
        const groupMetadata = await conn.groupMetadata(chatId);
        const participants = groupMetadata.participants.map(v => v.id);

        const botId = conn.user?.id?.split(':')[0] + '@s.whatsapp.net';
        const filteredParticipants = participants.filter(p => p !== botId);

        if (filteredParticipants.length === 0) {
            return m.reply(`${BRAND.emoji} *لا يوجد أعضاء*`);
        }

        /* ✅ اختيار عشوائي */
        const randomId = filteredParticipants[Math.floor(Math.random() * filteredParticipants.length)];
        const randomUser = await getUserName(conn, randomId);
        const randomChallenge = CHALLENGES[Math.floor(Math.random() * CHALLENGES.length)];

        await conn.sendMessage(chatId, { react: { text: '👑', key: m.key } });

        /* ✅ تصميم مضغوط — بدون آيات */
        const bodyText = `${BRAND.emoji} *تاج عشوائي*
━━━━━
👤 @${randomUser}
🔥 ${randomChallenge}
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`;

        /* ✅ الأزرار */
        const buttons = [
            {
                name: 'quick_reply',
                params: {
                    display_text: `👑 تاج جديد`,
                    id: `.تاج`
                }
            },
            {
                name: 'cta_url',
                params: {
                    display_text: `📢 قناة البوت`,
                    url: BRAND.channelLink
                }
            }
        ];

        /* ✅ إرسال — بدون صورة */
        try {
            return await conn.sendButton(chatId, {
                bodyText: bodyText,
                footerText: `${BRAND.emoji} ${BRAND.botName}`,
                buttons: buttons,
                mentions: [randomId],
                newsletter: {
                    name: BRAND.channelName,
                    jid: BRAND.channelId
                },
                interactiveConfig: { buttons_limits: 20 }
            }, m);
        } catch (e) {
            /* 🅱️ Fallback نصي */
            await conn.sendMessage(chatId, {
                text: bodyText,
                mentions: [randomId],
                contextInfo: {
                    mentionedJid: [randomId],
                    forwardingScore: 1,
                    isForwarded: true,
                    forwardedNewsletterMessageInfo: {
                        newsletterJid: BRAND.channelId,
                        newsletterName: BRAND.channelName,
                        serverMessageId: -1
                    }
                }
            }, { quoted: m });
        }

    } catch (error) {
        console.error('❌ خطأ:', error);
        
        await conn.sendMessage(chatId, {
            text: `${BRAND.emoji} *حدث خطأ*
━━━━━
📌 حاول مرة أخرى
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`,
            contextInfo: {
                forwardingScore: 1,
                isForwarded: true,
                forwardedNewsletterMessageInfo: {
                    newsletterJid: BRAND.channelId,
                    newsletterName: BRAND.channelName,
                    serverMessageId: -1
                }
            }
        }, { quoted: m });
    }
};

