/* ═══════════════════════════════════════════
   🎯 المعالج الرئيسي — بدون آيات
   ═══════════════════════════════════════════ */
const handler = async (m, { conn, args, participants }) => {
    const chatId = m.chat;

    try {
        /* ✅ تحديد الهدف — منشن أو رد */
        let userToInsult = null;

        /* 1️⃣ المنشن */
        if (m.mentionedJid && m.mentionedJid.length > 0) {
            userToInsult = m.mentionedJid[0];
        }
        /* 2️⃣ الرد على رسالة */
        else if (m.quoted?.sender) {
            userToInsult = m.quoted.sender;
        }
        /* 3️⃣ الرقم في النص */
        else if (args.length > 0) {
            const possibleJid = args[0].replace(/[^0-9]/g, '') + '@s.whatsapp.net';
            const isParticipant = participants?.some(p => p.id === possibleJid);
            if (isParticipant) {
                userToInsult = possibleJid;
            }
        }

        /* ✅ التحقق */
        if (!userToInsult) {
            return conn.sendMessage(chatId, {
                text: `${BRAND.emoji} *قمع*
━━━━━
📌 *الاستخدام:*
▸ .قمع @مستخدم
▸ أو رد على رسالة
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`
            }, { quoted: m });
        }

        /* ✅ اختيار عشوائي */
        const insult = insults[Math.floor(Math.random() * insults.length)];

        /* ✅ تصميم مضغوط — بدون آيات */
        const bodyText = `👤 @${userToInsult.split('@')[0]}
━━━━━
${insult}
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`;

        /* ✅ إرسال — بدون صورة */
        try {
            await conn.sendButton(chatId, {
                bodyText: bodyText,
                footerText: `${BRAND.emoji} ${BRAND.botName}`,
                buttons: [
                    {
                        name: 'quick_reply',
                        params: {
                            display_text: `😂 قمع جديد`,
                            id: `.قمع @${userToInsult.split('@')[0]}`
                        }
                    },
                    {
                        name: 'cta_url',
                        params: {
                            display_text: `📢 قناة البوت`,
                            url: BRAND.channelLink
                        }
                    }
                ],
                mentions: [userToInsult],
                newsletter: {
                    name: BRAND.channelName,
                    jid: BRAND.channelId
                },
                interactiveConfig: { buttons_limits: 2 }
            }, m);
        } catch (e) {
            /* 🅱️ Fallback نصي */
            await conn.sendMessage(chatId, {
                text: bodyText,
                mentions: [userToInsult],
                ...CHANNEL_INFO
            }, { quoted: m });
        }

    } catch (error) {
        console.error(`${BRAND.emoji} خطأ في أمر قمع:`, error);
        await conn.sendMessage(chatId, {
            text: `${BRAND.emoji} *حدث خطأ*
━━━━━
📌 حاول مرة أخرى`
        }, { quoted: m });
    }
};

