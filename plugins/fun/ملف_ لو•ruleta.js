const handler = async (m, { conn }) => {
    const chatId = m.chat;

    try {
        /* ✅ رياكت فوري */
        conn.sendMessage(chatId, {
            react: { text: '🤔', key: m.key }
        }).catch(() => {});

        const randomQuestion = lwQuestions[Math.floor(Math.random() * lwQuestions.length)];

        /* ✅ تصميم مضغوط — بدون آيات */
        const bodyText = `${BRAND.emoji} *لو خيروك* 🎭
━━━━━
${randomQuestion}
━━━━━
💬 *شارك إجابتك!*
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`;

        /* ✅ sendButton — بدون صورة */
        try {
            await conn.sendButton(chatId, {
                bodyText: bodyText,
                footerText: `${BRAND.emoji} ${BRAND.botName}`,
                buttons: [
                    {
                        name: 'quick_reply',
                        params: {
                            display_text: `🎭 سؤال آخر`,
                            id: `.لو`
                        }
                    },
                    {
                        name: 'quick_reply',
                        params: {
                            display_text: `💬 صراحة`,
                            id: `.صراحة`
                        }
                    },
                    {
                        name: 'cta_url',
                        params: {
                            display_text: `📢 قناة البوت`,
                            url: BRAND.channelLink
                        }
                    }
                ],
                mentions: [m.sender],
                newsletter: {
                    name: BRAND.channelName,
                    jid: BRAND.channelId
                },
                interactiveConfig: { buttons_limits: 3 }
            }, m);
        } catch (e) {
            /* 🅱️ Fallback نصي */
            await conn.sendMessage(chatId, {
                text: bodyText,
                ...CHANNEL_INFO
            }, { quoted: m });
        }

    } catch (error) {
        console.error(`${BRAND.emoji} خطأ:`, error);
        await conn.sendMessage(m.chat, {
            text: `${BRAND.emoji} *حدث خطأ*
━━━━━
📌 حاول مرة أخرى`
        }, { quoted: m });
    }
};

