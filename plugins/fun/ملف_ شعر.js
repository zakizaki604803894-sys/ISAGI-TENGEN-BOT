/* ────────────────[دالة جلب قصيدة عشوائية]──────────────── */
function getRandomPoem() {
    const allTypes = Object.keys(arabicPoetryDatabase);
    const randomTypeKey = allTypes[Math.floor(Math.random() * allTypes.length)];
    const list = arabicPoetryDatabase[randomTypeKey] || [];
    const randomIndex = Math.floor(Math.random() * list.length);
    const poem = list[randomIndex] || 'لا توجد قصيدة متاحة حالياً.';
    return {
        poem,
        type: randomTypeKey,
        typeName: typeNames[randomTypeKey] || '📚 المكتبة'
    };
}

