const handler = async (m, { conn }) => {
    const chatId = m.chat;

    try {
        const { poem, type, typeName } = getRandomPoem();

        /* ✅ رياكت فوري */
        conn.sendMessage(chatId, {
            react: { text: '📜', key: m.key }
        }).catch(() => {});

        /* ✅ تصميم مضغوط — بدون آيات */
        const bodyText = `${BRAND.emoji} *قصيدة عربية* 📜
━━━━━
📖 *التصنيف:* ${typeName}
━━━━━
${poem}
━━━━━
📌 *لقصيدة أخرى:* .شعر
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`;

        /* ✅ sendButton — بدون صورة */
        try {
            await conn.sendButton(chatId, {
                bodyText: bodyText,
                footerText: `${BRAND.emoji} ${BRAND.botName}`,
                buttons: [
                    {
                        name: 'quick_reply',
                        params: {
                            display_text: `📜 قصيدة أخرى`,
                            id: `.شعر`
                        }
                    },
                    {
                        name: 'cta_url',
                        params: {
                            display_text: `📢 قناة البوت`,
                            url: BRAND.channelLink
                        }
                    }
                ],
                mentions: [m.sender],
                newsletter: {
                    name: BRAND.channelName,
                    jid: BRAND.channelId
                },
                interactiveConfig: { buttons_limits: 2 }
            }, m);
        } catch (e) {
            /* 🅱️ Fallback نصي */
            await conn.sendMessage(chatId, {
                text: bodyText,
                ...CHANNEL_INFO
            }, { quoted: m });
        }

    } catch (error) {
        console.error(`${BRAND.emoji} خطأ في أمر شعر:`, error);
        await conn.sendMessage(chatId, {
            text: `${BRAND.emoji} *حدث خطأ*
━━━━━
📌 حاول مرة أخرى`
        }, { quoted: m });
    }
};

