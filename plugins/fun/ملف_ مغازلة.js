/* ═══════════════════════════════════════════
   🎯 المعالج الرئيسي — بدون آيات
   ═══════════════════════════════════════════ */
const handler = async (m, { conn, args, participants }) => {
    const chatId = m.chat;

    try {
        /* ✅ تحديد الهدف — منشن أو رد */
        let userToFlirt = null;

        /* 1️⃣ المنشن */
        if (m.mentionedJid && m.mentionedJid.length > 0) {
            userToFlirt = m.mentionedJid[0];
        }
        /* 2️⃣ الرد على رسالة */
        else if (m.quoted?.sender) {
            userToFlirt = m.quoted.sender;
        }
        /* 3️⃣ الرقم في النص */
        else if (args.length > 0) {
            const possibleJid = args[0].replace(/[^0-9]/g, '') + '@s.whatsapp.net';
            const isParticipant = participants?.some(p => p.id === possibleJid);
            if (isParticipant) {
                userToFlirt = possibleJid;
            }
        }

        /* ✅ اختيار عشوائي */
        const flirtMessage = flirtMessages[Math.floor(Math.random() * flirtMessages.length)];

        /* ✅ تصميم مضغوط — بدون آيات */
        let bodyText;
        if (userToFlirt) {
            bodyText = `👤 @${userToFlirt.split('@')[0]}
━━━━━
💘 ${flirtMessage}
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`;
        } else {
            bodyText = `${BRAND.emoji} *مغازلة* 💘
━━━━━
${flirtMessage}
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`;
        }

        /* ✅ sendButton — بدون صورة */
        try {
            await conn.sendButton(chatId, {
                bodyText: bodyText,
                footerText: `${BRAND.emoji} ${BRAND.botName}`,
                buttons: [
                    {
                        name: 'quick_reply',
                        params: {
                            display_text: `💘 رسالة أخرى`,
                            id: `.مغازلة`
                        }
                    },
                    {
                        name: 'quick_reply',
                        params: {
                            display_text: `💛 مدح`,
                            id: `.مدح`
                        }
                    },
                    {
                        name: 'cta_url',
                        params: {
                            display_text: `📢 قناة البوت`,
                            url: BRAND.channelLink
                        }
                    }
                ],
                mentions: userToFlirt ? [userToFlirt] : [m.sender],
                newsletter: {
                    name: BRAND.channelName,
                    jid: BRAND.channelId
                },
                interactiveConfig: { buttons_limits: 3 }
            }, m);
        } catch (e) {
            /* 🅱️ Fallback نصي */
            await conn.sendMessage(chatId, {
                text: bodyText,
                mentions: userToFlirt ? [userToFlirt] : [m.sender],
                ...CHANNEL_INFO
            }, { quoted: m });
        }

    } catch (error) {
        console.error(`${BRAND.emoji} خطأ في أمر مغازلة:`, error);
        await conn.sendMessage(chatId, {
            text: `${BRAND.emoji} *حدث خطأ*
━━━━━
📌 حاول مرة أخرى`
        }, { quoted: m });
    }
};

