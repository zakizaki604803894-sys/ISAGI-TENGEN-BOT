let handler = async (m, { conn, usedPrefix }) => {
    conn.animeQuiz = conn.animeQuiz || {};
    let id = m.chat;

    if (id in conn.animeQuiz) {
        await m.reply(`${BRAND.emoji} *تحدي نشط!*
━━━━━
📌 أكمل التحدي الحالي`);
        return;
    }

    const randomIndex = Math.floor(Math.random() * animeQuestions.length);
    const [question, correctAnswer, options] = animeQuestions[randomIndex];
    const shuffledOptions = shuffleArray(options);

    /* ✅ تصميم مضغوط — بدون آيات */
    const bodyText = `${BRAND.emoji} *اختبار الأنمي* 🎌
━━━━━
📌 ${question}
⏰ ${(timeout / 1000).toFixed(0)}ث | 💰 ${poin}XP
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`;

    const buttons = shuffledOptions.map((opt, i) => ({
        name: 'quick_reply',
        params: {
            display_text: `${i + 1}. ${opt}`,
            id: `.quiz_ans_${i + 1}`
        }
    }));

    buttons.push({
        name: 'quick_reply',
        params: {
            display_text: `${BRAND.emoji} استسلم`,
            id: `.quiz_استسلم`
        }
    });

    /* ✅ sendButton — بدون صورة */
    await conn.sendButton(m.chat, {
        bodyText: bodyText,
        footerText: `${BRAND.emoji} ${BRAND.botName}`,
        buttons: buttons,
        mentions: [m.sender],
        newsletter: {
            name: BRAND.channelName,
            jid: BRAND.channelId
        },
        interactiveConfig: { buttons_limits: 5 }
    }, m);

    let timer = setTimeout(async () => {
        if (conn.animeQuiz[id]) {
            await m.reply(`${BRAND.emoji} *انتهى الوقت!* ⌛
✅ *الإجابة:* ${correctAnswer}
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`);
            delete conn.animeQuiz[id];
        }
    }, timeout);

    conn.animeQuiz[id] = {
        question: question,
        correctAnswer: correctAnswer,
        options: shuffledOptions,
        correctIndex: shuffledOptions.indexOf(correctAnswer) + 1,
        poin: poin,
        wrongGuesses: [],
        timer: timer
    };
};

/* ────────────────[معالجة الأزرار]──────────────── */
handler.before = async (m, { conn }) => {
    conn.animeQuiz = conn.animeQuiz || {};
    let id = m.chat;

    if (!(id in conn.animeQuiz)) return;

    const quizData = conn.animeQuiz[id];
    const correctAnswer = quizData.correctAnswer.toLowerCase().trim();
    const rewardPoin = quizData.poin;

    /* ✅ معالجة الأزرار */
    if (m.body?.startsWith('.quiz_ans_')) {
        const selectedIndex = parseInt(m.body.replace('.quiz_ans_', ''));
        const selectedOption = quizData.options[selectedIndex - 1];
        const isCorrect = selectedOption.toLowerCase().trim() === correctAnswer;

        clearTimeout(quizData.timer);

        if (isCorrect) {
            const result = await addExp(m.sender, rewardPoin);
            
            let msg = `${BRAND.emoji} *صحيح!* ✅
━━━━━
🎌 *الإجابة:* ${quizData.correctAnswer}
💰 *+${rewardPoin}XP* | 💵 *${(result.user.exp || 0).toLocaleString('ar-EG')}XP*`;
            
            if (result.leveledUp) {
                msg += `\n🎉 *ترقية!* ${result.levelUpMsg}`;
            }
            
            msg += `\n━━━━━\n${BRAND.emoji} *${BRAND.shortName}*`;
            
            await m.reply(msg);
            delete conn.animeQuiz[id];
        } else {
            await m.reply(`${BRAND.emoji} *غلط!* ❌
✅ *الإجابة:* ${quizData.correctAnswer}
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`);
            delete conn.animeQuiz[id];
        }
        return true;
    }

    /* ✅ استسلم */
    if (m.body === '.quiz_استسلم') {
        clearTimeout(quizData.timer);
        await m.reply(`${BRAND.emoji} *استسلمت!*
━━━━━
✅ *الإجابة:* ${quizData.correctAnswer}
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`);
        delete conn.animeQuiz[id];
        return true;
    }

    /* ✅ معالجة الردود النصية */
    const userAnswer = m.text?.toLowerCase().trim();
    if (!userAnswer) return;

    if (userAnswer === 'استسلم' || userAnswer === 'استسلام') {
        clearTimeout(quizData.timer);
        await m.reply(`${BRAND.emoji} *استسلمت!*
━━━━━
✅ *الإجابة:* ${quizData.correctAnswer}
━━━━━
${BRAND.emoji} *${BRAND.shortName}*`);
        delete conn.animeQuiz[id];
        return true;
    }

    const isCorrect = userAnswer === correctAnswer;
    if (isCorrect) {
        clearTimeout(quizData.timer);
        
        const result = await addExp(m.sender, rewardPoin);
        
        let msg = `${BRAND.emoji} *صحيح!* ✅
━━━━━
🎌 *الإجابة:* ${quizData.correctAnswer}
💰 *+${rewardPoin}XP* | 💵 *${(result.user.exp || 0).toLocaleString('ar-EG')}XP*`;
        
        if (result.leveledUp) {
            msg += `\n🎉 *ترقية!* ${result.levelUpMsg}`;
        }
        
        msg += `\n━━━━━\n${BRAND.emoji} *${BRAND.shortName}*`;
        
        await m.reply(msg);
        delete conn.animeQuiz[id];
        return true;
    }

    return false;
};

